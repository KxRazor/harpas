//! Rust code generation from the schema
//!
//! The generated code calls the protocol crate's hand-written runtime in `crate::codec`: the `Encode` and
//! `Decode` traits, `DecodeError`, and one `read_*`/`write_*` function per wire type.

use std::fmt::Write;

use crate::schema::{
    Bitfield, Direction, Enum, Field, Flags, Packet, Prim, State, Type, Union, Version,
};

/// Rust keywords that need a raw identifier when used as field names.
const KEYWORDS: [&str; 38] = [
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
    "pub", "ref", "return", "self", "static", "struct", "super", "trait", "true", "type", "unsafe",
    "use", "where", "while",
];

/// Generates the codecs of every version, as the contents of one Rust file.
pub fn generate(versions: &[Version]) -> String {
    let mut out = Out::default();
    out.line("// Generated by harpas-protocol-codegen from the protocol schema. Do not edit.");
    for version in versions {
        out.line("");
        out.line(&format!(
            "/// Java Edition {} (protocol {}).",
            version.minecraft, version.protocol
        ));
        out.open(&format!("pub mod {}", version.module_name()));
        out.line("/// Protocol version number sent in the Handshake packet.");
        out.line(&format!("pub const PROTOCOL: i32 = {};", version.protocol));
        out.line("/// Name of the Minecraft version.");
        out.line(&format!(
            "pub const MINECRAFT_VERSION: &str = {:?};",
            version.minecraft
        ));
        for state in &version.states {
            state_module(&mut out, version, state);
        }
        out.close();
    }
    out.text
}

fn state_module(out: &mut Out, version: &Version, state: &State) {
    out.line("");
    out.line(&format!(
        "/// {} state of Java Edition {}.",
        title(&state.name),
        version.minecraft
    ));
    out.open(&format!("pub mod {}", state.name));
    out.line("#[allow(unused_imports)]");
    out.line("use crate::codec::{self, Decode, DecodeError, Encode};");
    if !state.externs.is_empty() {
        // The whole module, so that the types the externs are made of can be named too.
        out.line(&format!(
            "pub use crate::hand_written::{}::{}::*;",
            version.module_name(),
            state.name
        ));
    }
    for (name, item) in &state.enums {
        enum_type(out, name, item);
    }
    for (name, item) in &state.flags {
        flags_type(out, name, item);
    }
    for (name, item) in &state.bitfields {
        bitfield_type(out, name, item);
    }
    for (name, item) in &state.unions {
        union_type(out, name, item);
    }
    for (name, item) in &state.structs {
        struct_type(out, name, &item.doc, &item.fields);
    }
    for direction in [Direction::Clientbound, Direction::Serverbound] {
        direction_module(out, state, direction);
    }
    out.close();
}

fn direction_module(out: &mut Out, state: &State, direction: Direction) {
    let packets = state.packets(direction);
    out.line("");
    out.line(&format!(
        "/// Packets sent {}.",
        if direction == Direction::Clientbound {
            "by the server"
        } else {
            "by the client"
        }
    ));
    out.open(&format!("pub mod {}", direction.name()));
    out.line("#[allow(unused_imports)]");
    out.line("use super::*;");
    for packet in packets {
        struct_type(out, &packet.name, &packet.doc, &packet.fields);
        out.line("");
        out.open(&format!("impl {}", packet.name));
        out.line("/// Packet ID.");
        out.line(&format!("pub const ID: i32 = {:#04x};", packet.id));
        out.close();
    }
    packet_enum(out, state, direction, packets);
    out.close();
}

fn packet_enum(out: &mut Out, state: &State, direction: Direction, packets: &[Packet]) {
    out.line("");
    out.line(&format!(
        "/// Every {} packet of the {} state.",
        direction.name(),
        title(&state.name)
    ));
    out.line("#[derive(Debug, Clone, PartialEq)]");
    out.open("pub enum Packet");
    for packet in packets {
        out.line(&format!("/// {}", first_line(&packet.doc)));
        out.line(&format!("{0}({0}),", packet.name));
    }
    out.close();

    out.line("");
    out.open("impl Packet");
    out.line("/// Packet ID.");
    out.open("pub fn id(&self) -> i32");
    match_packets(out, packets, |name| format!("{name}::ID"));
    out.close();
    out.line("");
    out.line("/// Name of the packet's type, for logs.");
    out.open("pub fn name(&self) -> &'static str");
    match_packets(out, packets, |name| format!("{name:?}"));
    out.close();
    out.line("");
    out.line("/// Appends the packet ID and the packet to `buf`, without the length prefix.");
    out.open("pub fn encode(&self, buf: &mut Vec<u8>)");
    if packets.is_empty() {
        out.line("let _ = buf;");
        out.line("match *self {}");
    } else {
        out.line("codec::write_varint(buf, self.id());");
        out.open("match self");
        for packet in packets {
            out.line(&format!(
                "Self::{}(packet) => packet.encode(buf),",
                packet.name
            ));
        }
        out.close();
    }
    out.close();
    out.line("");
    out.line(
        "/// Decodes a whole packet, from its ID to its last byte, without the length prefix.",
    );
    out.open("pub fn decode(mut input: &[u8]) -> Result<Self, DecodeError>");
    out.line("let input = &mut input;");
    if packets.is_empty() {
        out.line("Err(DecodeError::UnknownPacket(codec::read_varint(input)?))");
    } else {
        out.open("let packet = match codec::read_varint(input)?");
        for packet in packets {
            out.line(&format!(
                "{0}::ID => Self::{0}({0}::decode(input)?),",
                packet.name
            ));
        }
        out.line("id => return Err(DecodeError::UnknownPacket(id)),");
        out.close_with("};");
        out.line("codec::expect_end(input)?;");
        out.line("Ok(packet)");
    }
    out.close();
    out.close();

    for packet in packets {
        out.line("");
        out.open(&format!("impl From<{}> for Packet", packet.name));
        out.open(&format!("fn from(packet: {}) -> Self", packet.name));
        out.line(&format!("Self::{}(packet)", packet.name));
        out.close();
        out.close();
    }
}

fn match_packets(out: &mut Out, packets: &[Packet], value: impl Fn(&str) -> String) {
    if packets.is_empty() {
        out.line("match *self {}");
        return;
    }
    out.open("match self");
    for packet in packets {
        out.line(&format!(
            "Self::{}(_) => {},",
            packet.name,
            value(&packet.name)
        ));
    }
    out.close();
}

fn enum_type(out: &mut Out, name: &str, item: &Enum) {
    let variants = item.variants();
    out.line("");
    doc(out, &item.doc);
    out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    out.open(&format!("pub enum {name}"));
    for (variant, value) in &variants {
        out.line(&format!("/// Sent as `{value}`."));
        out.line(&format!("{variant},"));
    }
    out.close();

    let repr = item.repr;
    out.line("");
    out.open(&format!("impl Encode for {name}"));
    out.open("fn encode(&self, buf: &mut Vec<u8>)");
    out.open("let value = match self");
    for (variant, value) in &variants {
        out.line(&format!("Self::{variant} => {value},"));
    }
    out.close_with("};");
    out.line(&format!("codec::write_{}(buf, value);", repr.name()));
    out.close();
    out.close();

    out.line("");
    out.open(&format!("impl Decode for {name}"));
    out.open("fn decode(input: &mut &[u8]) -> Result<Self, DecodeError>");
    out.open(&format!("match codec::read_{}(input)?", repr.name()));
    for (variant, value) in &variants {
        out.line(&format!("{value} => Ok(Self::{variant}),"));
    }
    out.line(&format!(
        "value => Err(DecodeError::UnknownEnumValue {{ name: {name:?}, value: i64::from(value) }}),"
    ));
    out.close();
    out.close();
    out.close();
}

fn union_type(out: &mut Out, name: &str, item: &Union) {
    let tag = |value: i64| match item.tag {
        Prim::Bool => (value != 0).to_string(),
        _ => value.to_string(),
    };
    out.line("");
    doc(out, &item.doc);
    out.line("#[derive(Debug, Clone, PartialEq)]");
    out.open(&format!("pub enum {name}"));
    for variant in &item.variants {
        if let Some(text) = &variant.doc {
            doc(out, text);
            out.line("///");
        }
        match (variant.tag, &variant.ty) {
            (None, None) => {
                out.line("/// Sent with any other tag, which it holds.");
                out.line(&format!("{}({}),", variant.name, item.tag.rust_type()));
            }
            (None, Some(ty)) => {
                out.line("/// Sent with any other tag, which it holds, followed by the value.");
                out.line(&format!(
                    "{}({}, {}),",
                    variant.name,
                    item.tag.rust_type(),
                    rust_type(ty)
                ));
            }
            (Some(value), ty) => {
                out.line(&format!("/// Sent with tag `{}`.", tag(value)));
                match ty {
                    Some(ty) => out.line(&format!("{}({}),", variant.name, rust_type(ty))),
                    None => out.line(&format!("{},", variant.name)),
                }
            }
        }
    }
    out.close();

    out.line("");
    out.open(&format!("impl Encode for {name}"));
    out.open("fn encode(&self, buf: &mut Vec<u8>)");
    out.open("match self");
    for variant in &item.variants {
        let write = |value: &str| format!("codec::write_{}(buf, {value})", item.tag.name());
        match (variant.tag, &variant.ty) {
            (None, None) => out.line(&format!(
                "Self::{}(tag) => {},",
                variant.name,
                write("*tag")
            )),
            (None, Some(ty)) => {
                out.open(&format!("Self::{}(tag, value) =>", variant.name));
                out.line(&format!("{};", write("*tag")));
                out.line(&format!("{};", encode(ty, "value", true)));
                out.close();
            }
            (Some(value), Some(ty)) => {
                out.open(&format!("Self::{}(value) =>", variant.name));
                out.line(&format!("{};", write(&tag(value))));
                out.line(&format!("{};", encode(ty, "value", true)));
                out.close();
            }
            (Some(value), None) => {
                out.line(&format!(
                    "Self::{} => {},",
                    variant.name,
                    write(&tag(value))
                ));
            }
        }
    }
    out.close();
    out.close();
    out.close();

    out.line("");
    out.open(&format!("impl Decode for {name}"));
    out.open("fn decode(input: &mut &[u8]) -> Result<Self, DecodeError>");
    out.open(&format!("match codec::read_{}(input)?", item.tag.name()));
    for variant in &item.variants {
        match (variant.tag, &variant.ty) {
            (None, _) => {}
            (Some(value), Some(ty)) => out.line(&format!(
                "{} => Ok(Self::{}({}?)),",
                tag(value),
                variant.name,
                decode(ty)
            )),
            (Some(value), None) => {
                out.line(&format!("{} => Ok(Self::{}),", tag(value), variant.name));
            }
        }
    }
    match item.variants.iter().find(|variant| variant.default) {
        Some(variant) => match &variant.ty {
            None => out.line(&format!("tag => Ok(Self::{}(tag)),", variant.name)),
            Some(ty) => out.line(&format!(
                "tag => Ok(Self::{}(tag, {}?)),",
                variant.name,
                decode(ty)
            )),
        },
        // Both values of a `bool` tag can be covered, and then there is nothing left to reject.
        None if item.tag == Prim::Bool && item.variants.len() == 2 => {}
        None => out.line(&format!(
            "value => Err(DecodeError::UnknownEnumValue {{ name: {name:?}, value: i64::from(value) }}),"
        )),
    }
    out.close();
    out.close();
    out.close();
}

/// `value as u64`, without a cast when it already is one.
fn as_u64(value: &str, prim: Prim) -> String {
    if prim == Prim::U64 {
        value.to_owned()
    } else {
        format!("{value} as u64")
    }
}

/// `bits as <prim>` from a `u64`, without a cast when it already is one.
fn from_u64(bits: &str, prim: Prim) -> String {
    if prim == Prim::U64 {
        bits.to_owned()
    } else {
        format!("{bits} as {}", prim.rust_type())
    }
}

fn flags_type(out: &mut Out, name: &str, item: &Flags) {
    let bits = item.ordered();
    out.line("");
    doc(out, &item.doc);
    out.line("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]");
    out.open(&format!("pub struct {name}"));
    for (flag, bit) in &bits {
        out.line(&format!("/// Bit {bit}."));
        out.line(&format!("pub {}: bool,", ident(flag)));
    }
    out.close();

    out.line("");
    out.open(&format!("impl Encode for {name}"));
    out.open("fn encode(&self, buf: &mut Vec<u8>)");
    out.line("let mut bits = 0u64;");
    for (flag, bit) in &bits {
        out.line(&format!(
            "if self.{} {{ bits |= {:#x}; }}",
            ident(flag),
            1u64 << bit
        ));
    }
    out.line(&format!(
        "codec::write_{}(buf, {});",
        item.repr.name(),
        from_u64("bits", item.repr)
    ));
    out.close();
    out.close();

    out.line("");
    out.open(&format!("impl Decode for {name}"));
    out.line("/// Bits without a flag are ignored, as vanilla does.");
    out.open("fn decode(input: &mut &[u8]) -> Result<Self, DecodeError>");
    out.line(&format!(
        "let bits = {};",
        as_u64(
            &format!("codec::read_{}(input)?", item.repr.name()),
            item.repr
        )
    ));
    out.open("Ok(Self");
    for (flag, bit) in &bits {
        out.line(&format!("{}: bits & {:#x} != 0,", ident(flag), 1u64 << bit));
    }
    out.close_with("})");
    out.close();
    out.close();
}

fn bitfield_type(out: &mut Out, name: &str, item: &Bitfield) {
    out.line("");
    doc(out, &item.doc);
    out.line("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]");
    out.open(&format!("pub struct {name}"));
    let mut low = item.repr.int_size().expect("validated") * 8;
    let mut layout = Vec::new();
    for field in &item.fields {
        low -= field.bits;
        layout.push((field, low));
        if let Some(text) = &field.doc {
            doc(out, text);
        }
        out.line(&format!(
            "pub {}: {},",
            ident(&field.name),
            field.rust_type()
        ));
    }
    out.close();

    let mask = |bits: u32| {
        if bits == 64 {
            u64::MAX
        } else {
            (1u64 << bits) - 1
        }
    };
    out.line("");
    out.open(&format!("impl Encode for {name}"));
    out.open("fn encode(&self, buf: &mut Vec<u8>)");
    out.line("let mut bits = 0u64;");
    for (field, low) in &layout {
        let value = if field.rust_type() == "u64" {
            format!("self.{}", ident(&field.name))
        } else {
            format!("self.{} as u64", ident(&field.name))
        };
        let shift = if *low == 0 {
            String::new()
        } else {
            format!(" << {low}")
        };
        let masked = format!("{value} & {:#x}", mask(field.bits));
        if shift.is_empty() {
            out.line(&format!("bits |= {masked};"));
        } else {
            out.line(&format!("bits |= ({masked}){shift};"));
        }
    }
    out.line(&format!(
        "codec::write_{}(buf, {});",
        item.repr.name(),
        from_u64("bits", item.repr)
    ));
    out.close();
    out.close();

    out.line("");
    out.open(&format!("impl Decode for {name}"));
    out.open("fn decode(input: &mut &[u8]) -> Result<Self, DecodeError>");
    out.line(&format!(
        "let bits = {};",
        as_u64(
            &format!("codec::read_{}(input)?", item.repr.name()),
            item.repr
        )
    ));
    out.open("Ok(Self");
    for (field, low) in &layout {
        let ty = field.rust_type();
        let value = if field.signed {
            // Move the field to the top bits, then shift it back down with sign extension.
            let up = 64 - low - field.bits;
            let down = 64 - field.bits;
            let up = if up == 0 {
                "bits".to_owned()
            } else {
                format!("(bits << {up})")
            };
            let shifted = format!("({up} as i64) >> {down}");
            if ty == "i64" {
                shifted
            } else {
                format!("({shifted}) as {ty}")
            }
        } else {
            let shifted = if *low == 0 {
                "bits".to_owned()
            } else {
                format!("(bits >> {low})")
            };
            let masked = format!("{shifted} & {:#x}", mask(field.bits));
            if ty == "u64" {
                masked
            } else {
                format!("({masked}) as {ty}")
            }
        };
        out.line(&format!("{}: {value},", ident(&field.name)));
    }
    out.close_with("})");
    out.close();
    out.close();
}

fn struct_type(out: &mut Out, name: &str, text: &str, fields: &[Field]) {
    out.line("");
    doc(out, text);
    out.line("#[derive(Debug, Clone, PartialEq)]");
    if fields.is_empty() {
        out.line(&format!("pub struct {name};"));
    } else {
        out.open(&format!("pub struct {name}"));
        for field in fields {
            if let Some(text) = &field.doc {
                doc(out, text);
            }
            out.line(&format!(
                "pub {}: {},",
                ident(&field.name),
                rust_type(&field.ty)
            ));
        }
        out.close();
    }

    out.line("");
    out.open(&format!("impl Encode for {name}"));
    if fields.is_empty() {
        out.line("fn encode(&self, _buf: &mut Vec<u8>) {}");
    } else {
        out.open("fn encode(&self, buf: &mut Vec<u8>)");
        for field in fields {
            let place = format!("self.{}", ident(&field.name));
            out.line(&format!("{};", encode(&field.ty, &place, false)));
        }
        out.close();
    }
    out.close();

    out.line("");
    out.open(&format!("impl Decode for {name}"));
    if fields.is_empty() {
        out.open("fn decode(_input: &mut &[u8]) -> Result<Self, DecodeError>");
        out.line("Ok(Self)");
    } else {
        out.open("fn decode(input: &mut &[u8]) -> Result<Self, DecodeError>");
        out.open("Ok(Self");
        for field in fields {
            out.line(&format!("{}: {}?,", ident(&field.name), decode(&field.ty)));
        }
        out.close_with("})");
    }
    out.close();
    out.close();
}

fn rust_type(ty: &Type) -> String {
    match ty {
        Type::Prim(prim) => prim.rust_type().to_owned(),
        Type::String { .. } => "String".to_owned(),
        Type::Bytes { .. } | Type::Rest { .. } => "Vec<u8>".to_owned(),
        Type::Option(inner) => format!("Option<{}>", rust_type(inner)),
        Type::Array { item, .. } => format!("Vec<{}>", rust_type(item)),
        Type::Nbt => "codec::Nbt".to_owned(),
        Type::OptionalNbt => "Option<codec::Nbt>".to_owned(),
        Type::Fixed(len) => format!("[u8; {len}]"),
        Type::Holder(inner) => format!("codec::Holder<{}>", rust_type(inner)),
        Type::LpVec3 => "codec::LpVec3".to_owned(),
        Type::Named(name) => name.clone(),
    }
}

/// An expression of type `Result<T, DecodeError>` that reads `ty` from `input: &mut &[u8]`.
fn decode(ty: &Type) -> String {
    let max = |max: &Option<usize>| max.map_or("usize::MAX".to_owned(), |max| max.to_string());
    match ty {
        Type::Prim(prim) => format!("codec::read_{}(input)", prim.name()),
        Type::String { max } => format!("codec::read_string(input, {max})"),
        Type::Bytes { max: limit } => format!("codec::read_bytes(input, {})", max(limit)),
        Type::Rest { max: limit } => format!("codec::read_rest(input, {})", max(limit)),
        Type::Option(inner) => format!("codec::read_option(input, {})", decoder(inner)),
        Type::Array { max: limit, item } => format!(
            "codec::read_array(input, {}, {})",
            max(limit),
            decoder(item)
        ),
        Type::Nbt => "codec::read_nbt(input)".to_owned(),
        Type::OptionalNbt => "codec::read_optional_nbt(input)".to_owned(),
        Type::Fixed(_) => "codec::read_fixed(input)".to_owned(),
        Type::Holder(inner) => format!("codec::read_holder(input, {})", decoder(inner)),
        Type::LpVec3 => "codec::LpVec3::decode(input)".to_owned(),
        Type::Named(name) => format!("{name}::decode(input)"),
    }
}

/// A function or closure that takes `input: &mut &[u8]` and returns `Result<T, DecodeError>`.
fn decoder(ty: &Type) -> String {
    match ty {
        Type::Prim(prim) => format!("codec::read_{}", prim.name()),
        Type::Nbt => "codec::read_nbt".to_owned(),
        Type::OptionalNbt => "codec::read_optional_nbt".to_owned(),
        Type::Fixed(_) => "codec::read_fixed".to_owned(),
        Type::LpVec3 => "codec::LpVec3::decode".to_owned(),
        Type::Named(name) => format!("{name}::decode"),
        other => format!("|input| {}", decode(other)),
    }
}

/// A statement that writes `ty` to `buf: &mut Vec<u8>`. `value` is a place of type `T`, or of type `&T`
/// when `by_ref` is true.
fn encode(ty: &Type, value: &str, by_ref: bool) -> String {
    let borrowed = if by_ref {
        value.to_owned()
    } else {
        format!("&{value}")
    };
    match ty {
        Type::Prim(prim) => {
            let copied = if by_ref {
                format!("*{value}")
            } else {
                value.to_owned()
            };
            format!("codec::write_{}(buf, {copied})", prim.name())
        }
        Type::String { .. } => format!("codec::write_string(buf, {borrowed})"),
        Type::Bytes { .. } => format!("codec::write_bytes(buf, {borrowed})"),
        Type::Rest { .. } => format!("codec::write_rest(buf, {borrowed})"),
        Type::Nbt => format!("codec::write_nbt(buf, {borrowed})"),
        Type::OptionalNbt => format!("codec::write_optional_nbt(buf, {borrowed})"),
        Type::Fixed(_) => format!("codec::write_fixed(buf, {borrowed})"),
        Type::Holder(inner) => format!("codec::write_holder(buf, {borrowed}, {})", encoder(inner)),
        Type::Option(inner) => {
            format!("codec::write_option(buf, {borrowed}, {})", encoder(inner))
        }
        Type::Array { item, .. } => {
            format!("codec::write_array(buf, {borrowed}, {})", encoder(item))
        }
        Type::Named(_) | Type::LpVec3 => format!("{value}.encode(buf)"),
    }
}

/// A function or closure that takes `buf: &mut Vec<u8>` and `value: &T` and writes the value.
fn encoder(ty: &Type) -> String {
    match ty {
        // The writers that take exactly `&T`; the others take `&str`, `&[u8]` or `T`.
        Type::Nbt => "codec::write_nbt".to_owned(),
        Type::OptionalNbt => "codec::write_optional_nbt".to_owned(),
        Type::Fixed(_) => "codec::write_fixed".to_owned(),
        other => format!("|buf, value| {}", encode(other, "value", true)),
    }
}

fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

fn doc(out: &mut Out, text: &str) {
    for line in text.lines() {
        out.line(format!("/// {line}").trim_end());
    }
}

fn first_line(text: &str) -> &str {
    text.lines().next().unwrap_or_default()
}

fn title(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
        .unwrap_or_default()
}

/// Indented output.
#[derive(Default)]
struct Out {
    text: String,
    depth: usize,
}

impl Out {
    fn line(&mut self, line: &str) {
        if !line.is_empty() {
            self.text.extend(std::iter::repeat_n("    ", self.depth));
        }
        let _ = writeln!(self.text, "{line}");
    }

    fn open(&mut self, head: &str) {
        self.line(&format!("{head} {{"));
        self.depth += 1;
    }

    fn close(&mut self) {
        self.close_with("}");
    }

    fn close_with(&mut self, tail: &str) {
        self.depth -= 1;
        self.line(tail);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nested_types_read_and_write_through_closures() {
        let ty = Type::parse("array(16, option(string(64)))").unwrap();
        assert_eq!(
            decode(&ty),
            "codec::read_array(input, 16, |input| codec::read_option(input, |input| codec::read_string(input, 64)))"
        );
        assert_eq!(
            encode(&ty, "self.names", false),
            "codec::write_array(buf, &self.names, |buf, value| \
             codec::write_option(buf, value, |buf, value| codec::write_string(buf, value)))"
        );
        assert_eq!(
            encode(&Type::Prim(Prim::U16), "value", true),
            "codec::write_u16(buf, *value)"
        );
    }
}
